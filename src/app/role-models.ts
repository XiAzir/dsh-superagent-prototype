/** Resolve role models and apply them to managed Sessions without changing DSH's global default. */
import type { Context } from '@deepseek-ai/cordis'
import type { Agent, ModelSelection } from '@deepseek-ai/dsh-agent'
import { ReasoningEffortId, boundContextSummary, createUserMessage } from '@deepseek-ai/dsh-llm'
import type { RoleModel } from '../policy.ts'

/** Resolve a configured route through the live provider; catalog membership is not a restriction. */
export async function resolveRoleModel(ctx: Context, model: RoleModel): Promise<ModelSelection> {
  const value = await ctx.llm.resolveCallConfig({ provider: model.provider, model: model.model,
    ...(model.reasoningEffort ? { reasoningEffort: ReasoningEffortId(model.reasoningEffort) } : {}) })
  return { provider: value.provider, model: value.model, ...(value.reasoningEffort ? { reasoningEffort: value.reasoningEffort } : {}) }
}

export interface RoleModelBinding {
  select(selection: ModelSelection): void
  dispose(): void
}

const sameSelection = (left: ModelSelection | undefined, right: ModelSelection): boolean => left?.provider === right.provider
  && left.model === right.model && left.reasoningEffort === right.reasoningEffort

function recordedSelection(agent: Agent): ModelSelection | undefined {
  const events = agent.session.snapshotEvents()
  for (let index = events.length - 1; index >= 0; index--) {
    const event = events[index]!
    if (event.type === 'model/selection') {
      const { provider, model, reasoningEffort } = event.data
      return { provider, model, ...reasoningEffort ? { reasoningEffort: ReasoningEffortId(reasoningEffort) } : {} }
    }
    if (event.type === 'request/header') {
      const { config, adapterDefaults } = event.data.header
      return { provider: config.provider, model: config.model,
        ...config.reasoningEffort === undefined || adapterDefaults?.reasoningEffort
          ? {} : { reasoningEffort: ReasoningEffortId(config.reasoningEffort) } }
    }
  }
  return undefined
}

/** Keep one role's selected model through prompt assembly and request routing while a running turn finishes on its original model. */
export function bindRoleModel(ctx: Context, agent: Agent): RoleModelBinding {
  let effective: ModelSelection | undefined
  let pending: ModelSelection | undefined
  let assembled: ModelSelection | undefined
  const finishTurn = () => { if (pending) { effective = pending; pending = undefined } }
  const disposers = [
    agent.ctx.on('system-prompt/assemble', async (_assembly, _context, next) => {
      const selected = effective
      const result = await next()
      assembled = selected
      return selected ? { ...result, variables: { ...result.variables, provider: selected.provider, model: selected.model } } : result
    }, { prepend: true }),
    agent.ctx.on('agent/request', async (_payload, next) => {
      const result = await next()
      if (!assembled) return result
      const { reasoningEffort: _inherited, ...rest } = result
      return { ...rest, ...assembled }
    }, { prepend: true }),
    agent.ctx.on('agent/pre-step', async ({ messages, signal, step }, next) => {
      const decision = await next()
      if (decision.kind === 'reject' || signal.aborted || !assembled
          || decision.messages.length === 0 && (step === 1 || messages.length > 0)) return decision
      const retained = decision.messages.filter(message => message.source.kind !== 'model-selection')
      const previous = agent.session.requestHeader()?.config
      if (!previous || previous.provider === assembled.provider && previous.model === assembled.model) {
        return retained.length === decision.messages.length ? decision : { ...decision, messages: retained }
      }
      const from = previous.provider === assembled.provider ? previous.model : `${previous.provider}/${previous.model}`
      const to = previous.provider === assembled.provider ? assembled.model : `${assembled.provider}/${assembled.model}`
      const notice = createUserMessage({ content: [{ type: 'text',
        text: `[model changed: assistant turns above this point were generated by ${from}; the session continues with ${to}]` }],
      source: { kind: 'model-selection', form: 'notice', summary: boundContextSummary(`${from} → ${to}`) } })
      return { ...decision, messages: [...retained, notice] }
    }, { prepend: true }),
    ctx.on('session/event', (session, event) => {
      if (session === agent.session && event.type === 'turn/end') finishTurn()
    }),
    ctx.on('agent/status', ({ agent: changed, status }) => {
      if (changed === agent && status === 'idle') finishTurn()
    }),
  ]
  return {
    select(selection) {
      if (agent.status === 'idle') { effective = selection; pending = undefined }
      else pending = selection
      if (!sameSelection(recordedSelection(agent), selection)) agent.session.append('model/selection', selection)
    },
    dispose() { for (const dispose of disposers) dispose() },
  }
}
